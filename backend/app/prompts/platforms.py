def normalize_sub_type(platform: str | None, sub_type: str | None) -> str:
    """把子形态收敛成合法值，非法值回落默认。

    有子形态的平台：知乎、公众号、今日头条、百家号；别的平台一律归空串
    （老数据、误传都往这里收敛）。
    传了不认识的值时回落默认形态——知乎落 `answer`（主力形态、字数区间最宽容），
    公众号 / 头条 / 百家号落 `article`（存量内容绝大多数是图文长文，回落它不改变行为）。
    """
    cfg = _SUBTYPE_TABLES.get(platform or "")
    if not cfg:
        return ""
    table, default = cfg
    st = (sub_type or "").strip()
    return st if st in table else default


def build_system_prompt(
    platform: str | None, topic: str = "", audience: str = "", sub_type: str = ""
) -> str:
    """拼装 system prompt。

    注意：平台 prompt 放最后，BASE_SYSTEM 固定在最前，提升缓存命中率。

    topic / audience 为空时**整行省略**，而不是填「用户将在对话中给出」——
    那种占位文案会被模型当成素材照抄进正文，用户拿到手就成了"需要填充的稿子"。
    """
    if not platform or platform not in PLATFORM_PROMPTS:
        return BASE_SYSTEM + "\n\n用户会描述需求，请按对应平台的规范输出成稿。"

    body = PLATFORM_PROMPTS[platform].format(topic=topic, audience=audience)
    if not topic:
        body = body.replace("主题：\n", "")
    if not audience:
        body = body.replace("目标读者：\n", "").replace("目标受众：\n", "")

    # 有子形态的平台（知乎 / 公众号 / 头条 / 百家号）：平台总纲之后追加形态模板。
    # 放在总纲后面而不是前面，是为了让模型先读到「平台读者脾气」再看具体篇幅要求。
    st = normalize_sub_type(platform, sub_type)
    if st:
        body += "\n\n" + _SUBTYPE_TABLES[platform][0][st]

    return BASE_SYSTEM + "\n\n" + body


