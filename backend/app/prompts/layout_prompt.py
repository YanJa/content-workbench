"""公众号排版提示词。

设计要点：**组件库原文必须塞进 system**。
gzh-design 技能明令「HTML 一律从组件库取，不要凭记忆手写」——
所以这里不写死任何组件 HTML，而是运行时把「选中主题的组件库 + 通用库」
拼进来，让模型照着抄、照着装配。

拼装顺序（命中缓存优先）：固定的规则在前，易变的组件库在后。
"""
from __future__ import annotations

# 排版引擎的角色与硬性输出契约（固定部分，放最前利于缓存）
LAYOUT_RULES = """你是「公众号排版引擎」。任务：把一篇 Markdown 文章装配成
可直接粘贴进微信公众号编辑器的**内联样式 HTML 片段**。

你会收到两份资产：某套主题的组件库（含文章骨架、组件 HTML、配方表、映射规则）
和一套通用增量库。**必须从组件库里取 HTML，不要凭记忆手写组件。**

严格遵守下面的输出契约（违反任何一条都算失败）：
1. 只输出纯 `<section>…</section>` 正文片段 ——
   **不要** `<!DOCTYPE>` / `<html>` / `<head>` / `<body>` / `<style>` / `<script>`。
2. 样式全部写成内联 `style="…"`；**禁止** `class` / `id` 属性。
3. 所有文字节点必须用 `<span leaf="">文字</span>` 包裹，否则粘贴后样式丢失。
4. 禁止：`<div>`（用 `<section>` 替代）、`position:fixed/absolute/sticky`、
   `float`、`@media`、`@keyframes`、`@import`、`display:grid`、CSS 变量 `var(--x)`。
5. 正文标点用中文全角（，。！？：；""''）；代码块/行内代码内保持原样。
6. **不得增删原文的实质内容**：原文每个段落、每张图都要转换。
7. 只做排版，不改写文案。若原文没有的句子，绝不新增。

排版流程（照组件库规则执行）：
- 先判定文章类型（教程/盘点/观点/访谈/数据复盘/随笔/案例）；
- 按组件库的「文章类型 → 组件组合配方表」选核心组件组合；
- 按「完整文章模板骨架」的**该主题骨架顺序**装配；
- 章节按 `##` 顺序自动编号 `01/02/03…`（末章若是结语用主题库指定的变体）；
- 每个正文段落主动挑 1–3 个关键词短语做下划线标记（用主题库/索引表的下划线 CSS）；
- 开场引言用引言卡组件，结尾按主题库要求处理签名区（无作者信息时用占位 `{{作者名}}`）。

占位符与关注卡（后端会做确定性替换，**原样保留、勿改写**）：
- `{{号名}}` `{{slogan}}` `{{作者名}}` `{{一句话简介}}` 视为「待填槽位」，
  **必须原样输出**（空格、花括号都不能动），后端会用真实值替换；
  不确定内容时也不要用你猜的文案顶替。
- 文末的关注卡里若有 `{{二维码}}` 占位，**同样原样保留**，后端会换成真实二维码图；
  没有配置二维码时后端会自动清掉这块，你不必操心。
- **只输出文末一处关注卡**：带 `<!--OPENING_FOLLOW_CARD-->` 标记的「开头关注卡」
  组件**不要装配**（连同其标记一起省略），正文直接从引言卡/首段开始。

只输出 HTML，不要任何解释、不要 Markdown 代码围栏、不要前后缀说明。
"""

# 回修提示（校验没过时追加，要求模型只修问题、别重排）
LAYOUT_FIX_HINT = """你上一次的排版产出未通过平台合规校验，下面是校验报出的问题：

{errors}

请**只修复这些问题**，其余排版保持不变，重新输出完整的 `<section>…</section>` 片段。
特别注意：所有中文文本都必须包在 `<span leaf="">` 里；不要出现 `<div>`/`class`/`id`；
不要出现半角标点（，。！？：；后面的半角 , ; ! ? 要换成全角）。
只输出 HTML。
"""


def build_layout_messages(
    markdown: str,
    theme_lib: str,
    common_lib: str,
    *,
    image_manifest: str = "",
) -> list[dict[str, str]]:
    """拼装排版的 messages。

    image_manifest：正文配图清单（换行分隔的 `图N 说明`），有配图时
    让模型在合适段落插入占位标记，后端再把真实 <img> 替换进去。
    """
    system = (
        LAYOUT_RULES
        + "\n\n===== 主题组件库（请严格照此取用 HTML）=====\n"
        + theme_lib
        + "\n\n===== 通用增量库 =====\n"
        + common_lib
    )

    user = "请把下面这篇 Markdown 排版成公众号 HTML：\n\n" + markdown
    if image_manifest:
        user += (
            "\n\n---\n本篇文章要配以下图片，请在对应的合适段落后插入占位标记 "
            "`<!--IMG:序号-->`（序号从 1 开始），我会把你插的标记替换成真实图片：\n"
            + image_manifest
            + "\n\n注意：标了【封面/头图】的那张是文章头图，放在正文最前面"
            "（标题/导语之后立即插入），不要放到文末。其余配图就近插在相关段落后。"
        )
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]
